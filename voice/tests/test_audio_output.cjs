'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const scope=vm.createContext({});vm.runInContext(fs.readFileSync('web/audio-output.js','utf8'),scope);
const describe=scope.ShengboAudioOutput.describe;
const diagnostic={available:true,devices:[{name:'Realtek',default:true}],browser_sessions:[{application:'Chrome',device_name:'Realtek',active:true,peak:.3}]};
let view=describe({status:'paused',connected_player:true},{ownsPlayback:true,paused:true},diagnostic);
assert.equal(view.status,'已暂停');assert.match(view.local,/暂停/);
assert.equal(view.device,'Realtek');assert.match(view.signal,/不代表伴侣已采集/);
view=describe({status:'playing',connected_player:true},{ownsPlayback:false},diagnostic);
assert.match(view.local,/其他窗口/);
view=describe({status:'playing'},{ownsPlayback:true,paused:false,muted:true,hasAudio:true},diagnostic);
assert.match(view.local,/静音/);
view=describe({status:'playing'},{ownsPlayback:true,paused:true,hasAudio:true},diagnostic);
assert.match(view.local,/未播放/);
view=describe({status:'paused'},{},{...diagnostic,browser_sessions:[]});
assert.match(view.signal,/已暂停/);
view=describe({},{},{...diagnostic,browser_sessions:[...diagnostic.browser_sessions,{device_name:'Steam',active:true,peak:.2}]});
assert.match(view.device,/多个/);assert.doesNotMatch(view.recommendation,/同名/);
view=describe({},{},{...diagnostic,stale:true});
assert.match(view.signal,/过期/);assert.match(view.recommendation,/过期/);
console.log('12 audio-output state/signal checks passed');
